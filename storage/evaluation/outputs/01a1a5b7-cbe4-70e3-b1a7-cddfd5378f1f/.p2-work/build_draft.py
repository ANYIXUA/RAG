def cjk_len(s):
    n = 0
    for ch in s:
        n += 2 if ord(ch) > 0x2E80 else 1
    return n

def needed_height(cell_texts_by_col, row):
    """estimate required row height from all wrapped columns in that row"""
    need = 0.0
    for col, txt in cell_texts_by_col.items():
        if not txt:
            continue
        letter = get_column_letter(col)
        width = ws.column_dimensions[letter].width or 8.43
        chars_per_line = max(4.0, (width - 1) / 1.05)  # mixed cjk vs latin; conservative
        lines = 0
        for seg in str(txt).split("\n"):
            lines += max(1, int(cjk_len(seg) / chars_per_line) + 1)
        need = max(need, lines * LINE_H)
    return need

